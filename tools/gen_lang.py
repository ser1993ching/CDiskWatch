import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, 'tools', 'lang', 'lang.tsv')
OUT = os.path.join(ROOT, 'CDiskWatch', 'src', 'i18n', 'Tables.g.cs')

CODES = ['zh-CN', 'ja-JP', 'en-US']
FIELDS = ['ZhCn', 'JaJp', 'EnUs']
PLACEHOLDER = re.compile(r'\{(\d+)\}')


def load():
    rows = []
    seen = set()
    for idx, line in enumerate(io.open(TSV, encoding='utf-8').read().splitlines(), 1):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        parts = line.split('\t')
        if len(parts) != 4:
            sys.exit('line %d: expected 4 columns, got %d' % (idx, len(parts)))
        key = parts[0].strip()
        if key in seen:
            sys.exit('line %d: duplicate key %s' % (idx, key))
        seen.add(key)
        rows.append((key, [p.strip() for p in parts[1:]]))
    return rows


def cs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t') + '"'


def main():
    rows = load()
    bad = 0
    for key, vals in rows:
        base = set(PLACEHOLDER.findall(vals[0]))
        for code, v in zip(CODES, vals):
            if not v:
                print('EMPTY  %-34s %s' % (key, code))
                bad += 1
                continue
            if set(PLACEHOLDER.findall(v)) != base:
                print('PLACEHOLDER %-30s %s -> %s vs zh %s' % (key, code, PLACEHOLDER.findall(v), sorted(base)))
                bad += 1
    if bad:
        sys.exit('%d problem(s)' % bad)

    out = []
    out.append('// <auto-generated>')
    out.append('// 由 tools/gen_lang.py 从 tools/lang/lang.tsv 生成，请勿手工修改。')
    out.append('// 修改文案的流程：改 tsv -> 运行 python tools/gen_lang.py -> dotnet build')
    out.append('// </auto-generated>')
    out.append('')
    out.append('namespace CDiskWatch;')
    out.append('')
    out.append('internal static class Tables')
    out.append('{')
    out.append('    public static readonly string[] Codes = { %s };' % ', '.join(cs(c) for c in CODES))
    out.append('')
    for i, field in enumerate(FIELDS):
        out.append('    /// <summary>%s（%d 条）</summary>' % (CODES[i], len(rows)))
        out.append('    public static readonly string[] %s =' % field)
        out.append('    {')
        for key, vals in rows:
            out.append('        %s, %s,' % (cs(key), cs(vals[i])))
        out.append('    };')
        out.append('')
    out.append('}')

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('generated %s: %d keys x %d languages' % (os.path.relpath(OUT, ROOT), len(rows), len(CODES)))


main()
